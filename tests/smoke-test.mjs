import { chromium } from 'playwright-core'

const BASE = process.argv[2] || 'http://localhost:4173'
const SHOTS = process.argv[3] || null
const results = []
const errors = []

function check(name, cond) {
  results.push({ name, ok: !!cond })
  console.log(`${cond ? 'PASS' : 'FAIL'}  ${name}`)
}

const browser = await chromium.launch({ channel: 'msedge', headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, acceptDownloads: true })
page.on('pageerror', (e) => errors.push(e.message))
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()) })

const shot = async (name) => { if (SHOTS) await page.screenshot({ path: `${SHOTS}/${name}.png`, fullPage: true }) }
const toastText = async () => (await page.locator('.toast-stack').innerText()).trim()
const modal = () => page.locator('.modal-box')
const title = () => page.locator('.page-title').innerText()
const sortItems = () => modal().locator('.sortable-list li').allInnerTexts()

// 1. 로그인
await page.goto(BASE)
check('로그인 전에는 로그인 화면으로 이동', page.url().includes('#/login'))
check('로그인 화면에 사이드바 없음', (await page.locator('.sidebar').count()) === 0)
await page.click('button[type=submit]')
check('빈 입력 시 오류 안내', (await page.locator('.login-error').innerText()).includes('사번과 비밀번호'))
await page.fill('#empNo', '9999999')
await page.fill('#pw', 'secret')
await page.click('text=표시')
check('비밀번호 표시 전환', (await page.getAttribute('#pw', 'type')) === 'text')
await page.click('text=숨기기')
await page.click('text=비밀번호 찾기')
