async function selectByName(sel, name) {
  const value = await page.locator(sel).evaluate((el, n) => [...el.options].find((o) => o.text.startsWith(n + ' '))?.value, name)
  if (!value) throw new Error(`${sel}에 ${name} 선택지가 없습니다`)
  await page.selectOption(sel, value)
}
