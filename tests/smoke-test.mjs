async function fillAll() {
  for (const q of await page.locator('.answer-sheet .q').all()) {
    if (await q.locator('.choice').count()) await q.locator('.choice').first().click()
    else if (await q.locator('textarea').count()) await q.locator('textarea').fill('성실하게 업무를 수행했습니다.')
    else if (await q.locator('input').count()) await q.locator('input').fill('공정 개선')
  }
}
